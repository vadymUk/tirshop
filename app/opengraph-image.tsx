// Latin-only text: the default ImageResponse font has no Cyrillic glyphs.
export default function OpengraphImage() {
  return new ImageResponse(
    (
      <div
        style={{
          width: "100%",
          height: "100%",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          background: "#18181b",
          color: "#fafafa",
          fontSize: 96,
          fontWeight: 700,
        }}
      >
        {siteConfig.name}
      </div>
    ),
    size,
  );
}
